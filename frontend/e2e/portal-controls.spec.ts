import { test, expect } from '@playwright/test'
import { prepare, profile } from './fixtures'
import { audit } from './audit'

for (const theme of ['light', 'dark'] as const) {
  for (const width of [320, 390, 768, 1024, 1440]) {
    test(`${theme} shared controls at ${width}px`, async ({ page }, info) => {
      test.skip(!!process.env.PORTAL_BASE_URL, 'The component fixture is available only on the local test server.')
      await page.setViewportSize({ width, height: 900 })
      await prepare(page, theme, false)
      await page.goto('/e2e/controls.html', { waitUntil: 'networkidle' })
      await expect(page.getByRole('heading', { name: 'Shared controls' })).toBeVisible()
      expect(await page.locator('.btn-primary > span').evaluate(el => getComputedStyle(el).color)).toBe(theme === 'dark' ? 'rgb(0, 0, 0)' : 'rgb(255, 255, 255)')
      expect(await page.locator('.btn-primary > span').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
      await page.getByRole('textbox', { name: 'Name', exact: true }).focus()
      expect(await page.locator('#name').evaluate(el => getComputedStyle(el).outlineStyle)).not.toBe('none')
      await audit(page, info, 'controls')
      await page.getByRole('switch').click()
      await expect(page.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
      await page.locator('.select-trigger').click()
      await expect(page.getByRole('option', { name: 'First option' })).toHaveAttribute('aria-selected', 'true')
      await audit(page, info, 'selected-option')
      await page.getByRole('option', { name: 'Second option' }).click()
      await page.locator('.date-picker-trigger').click()
      await audit(page, info, 'date-picker')
      await page.keyboard.press('Escape')
      await page.getByRole('heading', { name: 'Shared controls' }).click()
      await page.getByRole('button', { name: 'Help', exact: true }).click()
      await expect(page.locator('.ag-help-tooltip')).toBeVisible()
      await audit(page, info, 'tooltip')
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Open dialog' }).click()
      await expect(page.getByRole('dialog')).toBeVisible()
      await audit(page, info, 'dialog')
      await page.getByRole('button', { name: 'Done', exact: true }).click()
      await expect(page.getByRole('dialog')).not.toBeVisible()
      await page.getByRole('button', { name: 'Open legacy dialog', exact: true }).click()
      expect(await page.getByTestId('legacy-scrim').evaluate(el => getComputedStyle(el).backgroundColor)).toMatch(/0\.8\)/)
      await audit(page, info, 'legacy-dialog')
      await page.getByRole('button', { name: 'Close legacy dialog', exact: true }).click()
      await page.getByRole('button', { name: 'Show notification', exact: true }).click()
      const toast = await page.locator('.toast-region').boundingBox()
      expect(toast!.x).toBeGreaterThanOrEqual(15)
      expect(toast!.x + toast!.width).toBeLessThanOrEqual(width - 15)
      await audit(page, info, 'notification')
      await page.getByRole('button', { name: 'Close notification', exact: true }).click()
    })
  }

  test(`${theme} mobile navigation backdrop`, async ({ page }, info) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await prepare(page, theme)
    await page.goto('/career-concierge', { waitUntil: 'networkidle' })
    await page.getByRole('button', { name: 'Toggle menu', exact: true }).click()
    const backdrop = page.locator('.ag-modal-scrim')
    await expect(backdrop).toBeVisible()
    expect(await backdrop.evaluate(el => getComputedStyle(el).backgroundColor)).toMatch(/0\.8\)/)
    await audit(page, info, 'mobile-menu')
    await backdrop.click({ position: { x: 370, y: 300 } })
    await expect(backdrop).not.toBeVisible()
  })

  test(`${theme} paired schedule and error states`, async ({ page }, info) => {
    await prepare(page, theme)
    await page.route('**/api/v1/openclaw/career/profile*', route => route.fulfill({ json: { code: 0, data: { ...profile, telegram_paired: true } } }))
    await page.route('**/api/v1/openclaw/career/schedules*', route => route.fulfill({ json: { code: 0, data: { items: [{ id: 1, cron_expression: '0 9 * * 1-5', timezone: 'Europe/London', enabled: true, last_error: 'Delivery unavailable. Please check the connection and try again.' }] } } }))
    await page.goto('/career-concierge', { waitUntil: 'networkidle' })
    await expect(page.getByRole('button', { name: 'Add schedule', exact: true })).toBeEnabled()
    await audit(page, info, 'paired-schedule')
    await page.route('**/api/v1/openclaw/career/profile*', route => route.fulfill({ status: 503, json: { code: 503, message: 'Profile temporarily unavailable. Try again shortly.' } }))
    await page.getByRole('button', { name: 'Save profile', exact: true }).click()
    await expect(page.locator('.career-concierge-page > .error')).toBeVisible()
    await audit(page, info, 'profile-error')
  })
}
