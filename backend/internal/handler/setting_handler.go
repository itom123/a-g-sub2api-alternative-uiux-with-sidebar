// UnsubscribeNotificationEmail renders a confirmation page for optional
// notification email opt-outs. It intentionally does not change preferences.
// GET /api/v1/settings/email-unsubscribe?token=...
func (h *SettingHandler) UnsubscribeNotificationEmail(c *gin.Context) {
	setNotificationEmailUnsubscribeResponseHeaders(c)
	if h.notificationEmailService == nil {
		response.InternalError(c, "notification email service is not configured")
		return
	}
	token := strings.TrimSpace(c.Query("token"))
	if token == "" {
		response.BadRequest(c, "token is required")
		return
	}
	result, err := h.notificationEmailService.InspectUnsubscribe(c.Request.Context(), token)
	if err != nil {
		response.BadRequest(c, err.Error())
		return
	}
	action := c.Request.URL.EscapedPath() + "?token=" + url.QueryEscape(token)
	body := "<!doctype html><html><head><meta charset=\"utf-8\"><title>Confirm unsubscribe</title></head><body style=\"font-family:-apple-system,BlinkMacSystemFont,Segoe UI,sans-serif;padding:32px;\"><h1>Confirm unsubscribe</h1><p>Stop optional <strong>" + html.EscapeString(result.Event) + "</strong> emails for this address?</p><form method=\"post\" action=\"" + html.EscapeString(action) + "\"><input type=\"hidden\" name=\"" + notificationEmailOneClickField + "\" value=\"" + notificationEmailOneClickValue + "\"><button type=\"submit\">Unsubscribe</button></form></body></html>"
	c.Data(http.StatusOK, "text/html; charset=utf-8", []byte(body))
}

// UnsubscribeNotificationEmailOneClick handles the List-Unsubscribe-Post
// form body and the browser confirmation form. The signed token remains in
// the URL, so it stays compatible with existing unsubscribe links.
// POST /api/v1/settings/email-unsubscribe?token=...
func (h *SettingHandler) UnsubscribeNotificationEmailOneClick(c *gin.Context) {
	setNotificationEmailUnsubscribeResponseHeaders(c)
	if h.notificationEmailService == nil {
		response.InternalError(c, "notification email service is not configured")
		return
	}
	mediaType, _, err := mime.ParseMediaType(c.GetHeader("Content-Type"))
	if err != nil || !strings.EqualFold(mediaType, "application/x-www-form-urlencoded") {
		response.Error(c, http.StatusUnsupportedMediaType, "content type must be application/x-www-form-urlencoded")
		return
	}
	if strings.TrimSpace(c.PostForm(notificationEmailOneClickField)) != notificationEmailOneClickValue {
		response.BadRequest(c, "List-Unsubscribe must be One-Click")
		return
	}
	token := strings.TrimSpace(c.Query("token"))
	if token == "" {
		response.BadRequest(c, "token is required")
		return
	}
	result, err := h.notificationEmailService.Unsubscribe(c.Request.Context(), token)
	if err != nil {
		response.BadRequest(c, err.Error())
		return
	}
	body := "<!doctype html><html><head><meta charset=\"utf-8\"><title>Unsubscribed</title></head><body style=\"font-family:-apple-system,BlinkMacSystemFont,Segoe UI,sans-serif;padding:32px;\"><h1>Unsubscribed</h1><p>You have unsubscribed from optional <strong>" + html.EscapeString(result.Event) + "</strong> emails.</p></body></html>"
	c.Data(http.StatusOK, "text/html; charset=utf-8", []byte(body))
}

func setNotificationEmailUnsubscribeResponseHeaders(c *gin.Context) {
	c.Header("Cache-Control", "no-store, max-age=0")
	c.Header("Pragma", "no-cache")
	c.Header("Referrer-Policy", "no-referrer")
	c.Header("X-Content-Type-Options", "nosniff")
	c.Header("X-Robots-Tag", "noindex, nofollow")
	c.Header("Content-Security-Policy", "default-src 'none'; base-uri 'none'; form-action 'self'; style-src 'unsafe-inline'")
}

func publicLoginAgreementDocumentsToDTO(items []service.LoginAgreementDocument) []dto.LoginAgreementDocument {
	result := make([]dto.LoginAgreementDocument, 0, len(items))
	for _, item := range items {
		result = append(result, dto.LoginAgreementDocument{
			ID:        item.ID,
			Title:     item.Title,
			ContentMD: item.ContentMD,
		})
	}
	return result
}
